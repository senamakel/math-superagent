import subprocess, sys
# re-scan quickly with simpler exact-ish loop (small n=1e4)
def scan_b(d, n):
    sd = mp.sqrt(d)
    bestb=None; best=mp.mpf(10)
    for b in range(0, n+1):
        v = b*sd - pi
        err = mp.fabs(v - mp.nint(v))
        if err < best:
            best = err; bestb = b
    return bestb
