vals = [c[1] for c in coins]
n = len(vals)

# partition into maximal runs of equal consecutive difference (values strictly
# descending so differences negative). Also gather single-term runs.
runs = []
i = 0
while i < n:
    if i == n-1:
        runs.append((i,i))
        break
    d = vals[i+1]-vals[i]
    j = i+1
    while j+1 < n and vals[j+1]-vals[j] == d:
        j += 1
    runs.append((i,j))
    i = j+1

# Sum via arithmetic progression: for a run of L terms with first a and step d,
# sum = L*(first+last)//2 (exact integers; values are ints; product is even-safe
# via L*(first+last)//2 because AP sum integer).
ap_sum = 0
for (s,e) in runs:
    L = e-s+1
    if L == 1:
        ap_sum += vals[s]
    else:
        first,last = vals[s], vals[e]
        ap_sum += L*(first+last)//2

direct_sum = sum(vals)
