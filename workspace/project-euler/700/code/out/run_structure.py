idx = [c[0] for c in coins]
vals = [c[1] for c in coins]

def runs(seq):
    # find maximal runs of consecutive terms with constant first difference
    out = []
    i = 0
    n = len(seq)
    while i < n-1:
        d = seq[i+1]-seq[i]
        j = i+1
        while j+1 < n and seq[j+1]-seq[j] == d:
            j += 1
        if j-i >= 1:  # at least two steps
            out.append((i, j, d))
        i = j
    return out

