def ap_runs(seq):
    n = len(seq)
    diffs = [seq[i+1]-seq[i] for i in range(n-1)]
    runs = []
    i = 0
    while i < n-1:
        j = i
        d = diffs[i]
        while j < n-1 and diffs[j] == d:
            j += 1
        # run spans seq[i..j] inclusive (j-i+1 terms), diff d
        runs.append((i, j, d, j-i+1))
        i = j
    return runs

