# Recompute runs directly from constant-difference detection (not hand-typed)
def ap_runs(seq):
    n = len(seq)
    diffs = [seq[i+1]-seq[i] for i in range(n-1)]
    runs = []
    i = 0
    while i < n-1:
        j = i
        d = diffs[i]
        while j < n-1 and diffs[j] == d:
            j += 1
        runs.append((i, j, d, j-i+1))
        i = j
    return runs

runs = ap_runs(vals)
tot = 0
for (s,e,d,L) in runs:
    seg = vals[s:e+1]
    sm = sum(seg)
    assert sm == L*(2*seg[0]+(L-1)*d)//2
    tot += sm
print("total via recomputed runs:", tot)
print("matches direct:", tot == sum(vals))
