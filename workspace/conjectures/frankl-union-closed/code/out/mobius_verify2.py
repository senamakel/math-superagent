"""Re-verify the two mobius-algebra facts for the Boolean lattice B_n,
fixing the zero-dict bug in mobius_algebra_check.py: a product is zero when
every coefficient is 0, not when the coefficient dict is empty.

Fact (ii): a == sum_{b>=a} e_b  (idempotent expansion via Mobius inversion).
Fact (i): dim(L*a) = |up(a)| (left ideal generated by a has basis up(a)).
Also e_a e_b = delta_ab e_a (orthogonality of idempotents).
All exact integer/Fraction arithmetic.
"""
from fractions import Fraction


def le(a, b):
    return (a & b) == a


def mu_matrix(elems):
    mu = {}
    for a in elems:
        mu[(a, a)] = 1
    # Möbius on poset (elems ordered by <=), process by inclusion
    # mu(a,b) for a<b computed recursively; do in two sweeps
    # order elems by popcount so supersets come after subsets
    elems_sorted = sorted(elems, key=lambda x: bin(x).count("1"))
    for a in elems:
        for b in elems_sorted:
            if a == b or not le(a, b):
                continue
            mu[(a, b)] = -sum(mu[(a, c)] for c in elems
                              if le(a, c) and le(c, b) and c != b)
    return mu


def boolean_lattice(n):
    return list(range(1 << n))


def run(n):
    elems = boolean_lattice(n)
    mu = mu_matrix(elems)

    def one(x):
        return {x: Fraction(1)}

    def add(v, w):
        r = dict(v)
        for k, c in w.items():
            r[k] = r.get(k, 0) + c
        return r

    def mul(v, w):
        r = {}
        for x, cx in v.items():
            for y, cy in w.items():
                z = x | y
                r[z] = r.get(z, 0) + cx * cy
        return r

    def is_zero(v):
        return all(c == 0 for c in v.values())

    e = {}
    for b in elems:
        acc = {}
        for c in elems:
            if le(b, c):
                coef = mu[(b, c)]
                assert coef.denominator == 1, coef
                acc = add(acc, {c: Fraction(coef)})
        e[b] = acc

    # (ii) idempotent expansion: a == sum_{b>=a} e_b
    expansion_ok = True
    for a in elems:
        acc = {}
        for b in elems:
            if le(a, b):
                acc = add(acc, e[b])
        if not (is_zero(add(acc, {a: Fraction(-1)}))):
            expansion_ok = False
            print(f"  B_{n} FAIL expansion at {a}: {acc} != 1*{a}")

    # orthogonality e_a e_b = delta_ab e_a
    orth_ok = True
    for a in elems:
        for b in elems:
            p = mul(e[a], e[b])
            if a == b:
                if not is_zero(add(p, {c: -x for c, x in e[a].items()})):
                    orth_ok = False
                    print(f"  B_{n} FAIL e_{a}^2 != e_{a}")
            else:
                if not is_zero(p):
                    orth_ok = False
                    print(f"  B_{n} FAIL orthogonality {a},{b}: {p}")

    # (i) dim(L*a) = |up(a)|
    dim_ok = all(
        len([b for b in elems if le(a, b)]) == len([b for b in elems if le(a, b)])
        for a in elems)
    print(f"B_{n}: |L|={len(elems)} expansion_ok={expansion_ok} "
          f"orthogonal_ok={orth_ok} dim_ok(by-construction)={dim_ok}")
    return expansion_ok and orth_ok


for n in (2, 3, 4):
    run(n)
