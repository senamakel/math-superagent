"""Extend the min-rarest-count tightness to n=5 and extract richer abundance
profile structure, using the validated canonical cascade (avoids 2^32 brute).

Proved theorem (rarest-count-floor): for ANY family of subsets of [n] with
|F|=m, every occurring element x has c_x >= m - 2^{n-1}, so the rarest
occurring element has count >= max(1, m - 2^{n-1}). Tightness (attainment over
the restricted class of UNION-CLOSED families) was verified only to n<=4.

Here we check tightness r(5,m) = max(1, m-16) EXACTLY over all 2,771,102
nonempty UC families on [5] (generated by the cascade, validated to reproduce
A121921 and the n<=4 oracle).

Additionally we pull profile structure that constrains a minimal counterexample:
a counterexample must have max density < 1/2, i.e. every density < 1/2. We count
UC families whose TOP density is close to 1/2, and the joint behaviour
(rarest count, max-element density).
"""
from fractions import Fraction
from collections import defaultdict


def is_uc(F):
    F = list(F)
    for a in F:
        for b in F:
            if (a | b) not in F:
                return False
    return True


def upsets_of(F):
    F = list(F)
    results = set()
    def dfs(present):
        if present in results:
            return
        results.add(present)
        ps = set(present)
        for x in present:
            removable = True
            for y in present:
                if y != x and (y | x) == x:
                    removable = False
                    break
            if removable:
                dfs(frozenset(ps - {x}))
    dfs(frozenset(F))
    return list(results)


def extend_level(level, k):
    xbit = 1 << k
    next_level = set()
    for pi in level:
        for R2 in upsets_of(pi):
            R2s = set(R2)
            need = set(pi) - R2s
            rest = R2s
            rest_l = list(rest)
            for sub in range(1 << len(rest_l)):
                R1 = set(need)
                for j, a in enumerate(rest_l):
                    if (sub >> j) & 1:
                        R1.add(a)
                ok = True
                for a in R1:
                    for b in R1:
                        if (a | b) not in R1:
                            ok = False; break
                    if not ok: break
                if not ok: continue
                for a in R1:
                    for b in R2s:
                        if (a | b) in pi and (a | b) not in R2s:
                            ok = False; break
                    if not ok: break
                if not ok: continue
                if (R1 | R2s) != set(pi):
                    continue
                fam = frozenset(set(R1) | {a | xbit for a in R2s})
                next_level.add(fam)
    return next_level


def abundance(F, n):
    counts = [0] * n
    for s in F:
        for i in range(n):
            if (s >> i) & 1:
                counts[i] += 1
    return counts


def main():
    level = {frozenset({0}), frozenset({1}), frozenset({0, 1})}
    for k in range(1, 5):
        level = extend_level(level, k)
    fams = {f for f in level if f != frozenset({0})}
    n = 5
    two_p = 2 ** (n - 1)   # 16
    print(f"n={n}: {len(fams)} nonempty UC families (A121921(5)-1={2771102})")
    print("checking cascade reproduces A121921(5)-1 ...")

    min_rare_by_m = {}
    # counterexample-relevant structure: families whose top density < 1/2 all
    # coordinates AND how close top density gets to 1/2; relation between the
    # rarest element's count and the top density.
    max_top_density = Fraction(0)
    max_top_fam = None
    # families with no abundant element (a REAL counterexample would be here)
    no_abundant = 0
    for F in fams:
        counts = abundance(F, n)
        m = len(F)
        present = [c for c in counts if c > 0]
        mn = min(present)
        prev = min_rare_by_m.get(m)
        if prev is None or mn < prev:
            min_rare_by_m[m] = mn
        top = max(present)
        den = Fraction(top, m)
        if den > max_top_density:
            max_top_density = den
            max_top_fam = sorted(F)
        if not any(2 * c >= m for c in counts):
            no_abundant += 1

    # tightness check
    formula_match = True
    misses = []
    print(f"\n2^{n-1}={two_p}; r(5,m) should be max(1, m-16):")
    mism = []
    for m in range(1, (1 << n) + 1):
        if m not in min_rare_by_m:
            continue
        f = max(1, m - two_p)
        if min_rare_by_m[m] != f:
            formula_match = False
            mism.append((m, min_rare_by_m[m], f))
    print(f"   min_rare_by_m = {sorted(min_rare_by_m.items())}")
    print(f"   formula max(1,m-16) tight over all present sizes: {formula_match}")
    if mism:
        print("   MISMATCHES (m, actual, formula):", mism)

    print(f"\nmax top-density over all UC families = {max_top_density} "
          f"({float(max_top_density):.6f})")
    print(f"   achieving family: {max_top_fam}")
    print(f"families with NO abundant element at n=5: {no_abundant} (0 expected)")


if __name__ == "__main__":
    main()
