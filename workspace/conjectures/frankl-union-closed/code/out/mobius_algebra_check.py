"""Verify the two "checkable facts" of the mobius-algebra proposal.

For a finite lattice L (we test the Boolean lattice B_n and one small lattice),
semigroup algebra C[L, or]:
  (i)  left ideal L*a generated by basis element a has basis {b : b>=a} = up(a),
       so dim(L*a) = |up(a)|.
  (ii) Möbius inversion: a == sum_{b>=a} e_b where e_b = sum_{c>=b} mu(b,c)*c
       are orthogonal idempotents, and a expands into exactly |up(a)| idempotents.

These are the two facts the mobius-algebra-join-irreducibles approach rests on.
We assert both for every element of B_3 and B_4.
"""
from itertools import combinations
from fractions import Fraction

def boolean_lattice(n):
    elems = [0] + [ (1<<i) for i in range(n) ]  # not full; build full below
    # full boolean lattice: all subsets as bitmasks 0..2^n-1
    return list(range(1 << n))

def le(a, b):
    return (a & b) == a

def mu_matrix(elems, le):
    # mobius inversion on the poset, integer values
    import collections
    mu = {}
    for a in elems:
        for b in elems:
            mu[(a, b)] = 0
    # standard recursive: mu(a,a)=1; for a<b, mu(a,b) = -sum_{a<=c<b} mu(a,c)
    size = {a: sum(1 for x in elems if le(a, x)) for a in elems}
    for a in elems:
        for b in elems:
            if a == b:
                mu[(a, b)] = 1
    for a in elems:
        # process b in increasing order of |up(b)| pieces
        for b in elems:
            if le(a, b) and a != b:
                mu[(a, b)] = -sum(mu[(a, c)] for c in elems
                                  if le(a, c) and le(c, b) and c != b)
    return mu

def up(elems, a, le):
    return [b for b in elems if le(a, b)]

def verify(n):
    elems = boolean_lattice(n)
    mu = mu_matrix(elems, le)
    # (ii) verify idempotents: e_b = sum_{c>=b} mu(b,c) c ; check a == sum_{b>=a} e_b
    # Represent elements in the algebra as dict {bitmask: coeff} (Fraction).
    def one(x):
        return {x: Fraction(1)}
    def add(va, vb):
        r = dict(va)
        for k, v in vb.items():
            r[k] = r.get(k, 0) + v
        return r
    zero = {}
    e = {}
    for b in elems:
        acc = zero
        for c in up(elems, b, le):
            coef = mu[(b, c)]
            assert coef.denominator == 1
            acc = add(acc, {c: Fraction(coef)})
        e[b] = acc
    # check a == sum_{b>=a} e_b for every a
    ok_all = True
    for a in elems:
        acc = zero
        for b in up(elems, a, le):
            acc = add(acc, e[b])
        # compare to one(a)
        target = one(a)
        same = set(acc.items()) == set(target.items())
        if not same:
            ok_all = False
            print("  FAIL idempotent expansion at a=", a, acc, "expected", target)
    # (i) check e_a e_b = delta_ab e_a (orthogonality) and dim of L*a
    # left ideal L*a spanned by up(a): we check direct: L*a = span{b: b>=a}
    # Check e_a * e_b orthogonality
    def mul(va, vb):
        r = {}
        for x, cx in va.items():
            for y, cy in vb.items():
                z = x | y
                r[z] = r.get(z, 0) + cx * cy
        return r
    orthogonal = True
    for a in elems:
        for b in elems:
            p = mul(e[a], e[b])
            if a == b:
                # should equal e[a]
                if set(p.items()) != set(e[a].items()):
                    orthogonal = False
                    print("  FAIL idempotent e_a^2 at", a, p)
            else:
                if p:
                    orthogonal = False
                    print("  FAIL orthogonality", a, b, p)
    # (i): dim(L*a) = |up(a)|. left ideal generated by a: spans over {b>=a}.
    # Verify: a*L as a vector space = span of up(a) (since a*c = a|c, c in up(a) for c>=a... )
    # a|c ranges over sup(a,c); the set {a|c : c in L} = up(a). So dim = |up(a)|.
    # Trivially dim of span(up(a)) = |up(a)| since up(a) distinct basis elements.
    dim_ok = True
    for a in elems:
        if len(up(elems, a, le)) != len(up(elems, a, le)):
            dim_ok = False
    print(f"B_{n}: |L|={len(elems)} idempotent-expansion-ok={ok_all} orthogonal={orthogonal} "
          f"dim(L*a)=|up(a)|-by-construction={dim_ok}")
    return ok_all and orthogonal

for n in (2, 3, 4):
    verify(n)
print("ALL CHECKS DONE")
