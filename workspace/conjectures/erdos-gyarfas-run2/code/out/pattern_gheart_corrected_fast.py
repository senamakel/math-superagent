"""Pattern-finder: extend the corrected G-heart verification to n=8.

Same oracle verification as pattern_gheart_corrected.py, but replaces the
pairwise VF2 isomorphism dedup in the generator with an exact hash-based
canonical-form dedup (lib/canonical.canonical_key). This is still an EXACT
dedup: two graphs are isomorphic iff their canonical keys are equal, so each
isomorphism class is emitted exactly once. It avoids the O(N^2) pairwise VF2
scan that made n=8 intractable.

THEOREM USED (canonical forms, Diestel): the class of 2-connected graphs is
generated by ear decomposition (seed = all cycles, close under path-ears and
chords). Dedup by exact canonical form yields each isomorphism class once.
This is constructive generation of a well-defined class, not a search.
"""
import time
import networkx as nx
from lib.erdos_gyarfas import has_power_of_two_cycle
from lib.canonical import canonical_key as _canon_key


def _cycle_graph(n):
    return nx.cycle_graph(n)


def add_path_ear(G, u, v, k):
    H = G.copy()
    base = H.number_of_nodes()
    prev = u
    for i in range(k):
        w = base + i
        H.add_node(w)
        H.add_edge(prev, w)
        prev = w
    H.add_edge(prev, v)
    return H


def add_single_edge(G, u, v):
    H = G.copy()
    H.add_edge(u, v)
    return H


def generate_2connected_levels_canon(n_target):
    levels = {m: [] for m in range(3, n_target + 1)}
    seen = {m: set() for m in range(3, n_target + 1)}

    def add_to_level(H):
        m = H.number_of_nodes()
        if m > n_target:
            return False
        key = _canon_key(H)
        if key in seen[m]:
            return False
        seen[m].add(key)
        levels[m].append(H)
        return True

    for l in range(3, n_target + 1):
        add_to_level(_cycle_graph(l))

    worklist = [G for ms in levels.values() for G in ms]
    while worklist:
        G = worklist.pop()
        m = G.number_of_nodes()
        verts = list(G.nodes())
        vert_set = set(verts)
        for k in range(1, n_target - m + 1):
            for u in verts:
                for v in verts:
                    if u == v:
                        continue
                    H = add_path_ear(G, u, v, k)
                    if add_to_level(H):
                        worklist.append(H)
        for i in range(len(verts)):
            for j in range(i + 1, len(verts)):
                u, v = verts[i], verts[j]
                if not G.has_edge(u, v):
                    H = add_single_edge(G, u, v)
                    if add_to_level(H):
                        worklist.append(H)
    return levels


def min_degree(G):
    return min(dict(G.degree()).values()) if G.number_of_nodes() > 0 else 0


def run(N):
    t0 = time.time()
    levels = generate_2connected_levels_canon(N)
    print(f"generation time: {time.time()-t0:.1f}s", flush=True)
    print("n | #2conn | #delta>=3 | #with_2power | verdict")
    for n in range(3, N + 1):
        graphs = levels.get(n, [])
        n_d3 = 0
        n_ok = 0
        all_ok = True
        bad = None
        for G in graphs:
            if min_degree(G) >= 3:
                n_d3 += 1
                ok, L = has_power_of_two_cycle({v: set(G.neighbors(v)) for v in G.nodes()})
                if ok:
                    n_ok += 1
                else:
                    all_ok = False
                    if bad is None:
                        bad = (G.edges(), L)
        v = "VERIFIED" if all_ok else "COUNTEREXAMPLE"
        print(f"{n} | {len(graphs)} | {n_d3} | {n_ok} | {v}", flush=True)
        if bad:
            print("   counterexample edges:", bad)
    print(f"TOTAL WALL TIME: {time.time()-t0:.1f}s", flush=True)


if __name__ == "__main__":
    import sys
    N = int(sys.argv[1]) if len(sys.argv) > 1 else 7
    run(N)
